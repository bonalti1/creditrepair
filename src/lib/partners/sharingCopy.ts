/** "Cómo funciona Credalti": the one page a partner shares, with their name. */
export function howItWorksCopy(locale: "es" | "en", partner: { name: string; company: string | null }, commissionsEnabled: boolean) {
  const n = first(partner.name);
  const who = partner.company ? `${partner.name}, ${partner.company}` : partner.name;
  if (locale === "en") {
    return {
      eyebrow: `Shared by ${who}`,
      title: `How ${brand} works`,
      lead: `A service in English and Spanish to review your credit report and dispute what you say is wrong. Our team prepares and mails your letters.`,
      stepsTitle: "Step by step",
      steps: [
        { title: "You talk with the team on WhatsApp", body: "A person explains the plan and its price, in writing, before you sign anything." },
        { title: "You read your rights and sign", body: "You have 3 business days to cancel at no cost. No work starts before then." },
        { title: "You review your report in the app", body: "You decide what is inaccurate. Nobody decides for you." },
        { title: "The team mails your letters", body: `The bureaus have about ${CASE_RESPONSE_DAYS} days to answer. You see every step with dates in your app.` },
      ],
      honestTitle: "What we do not do",
      honest: [
        "We do not promise results: no points, no dates, no approvals. The bureaus decide and results vary.",
        "We do not dispute anything you say is correct.",
        `Never give your Social Security number or your report to ${n}. You give your details yourself, in your own account.`,
      ],
      sharingTitle: `${n} and your progress`,
      sharing: `If you want, you can let ${n} see how your case is going, without seeing your credit. It is your choice, and you can stop it whenever you want.`,
      fees: commissionsEnabled ? `${n} receives a commission if they refer you to ${brand}.` : `${n} receives no payment for referring you.`,
      cta: "Get started",
      footer: "Results vary case by case.",
    };
  }
  return {
    eyebrow: `Te lo comparte ${who}`,
    title: `Cómo funciona ${brand}`,
    lead: "Un servicio en inglés y en español para revisar tu reporte de crédito y disputar lo que tú digas que está mal. Nuestro equipo prepara y envía tus cartas.",
    stepsTitle: "Paso a paso",
    steps: [
      { title: "Hablas con el equipo por WhatsApp", body: "Una persona te explica el plan y su precio, por escrito, antes de que firmes nada." },
      { title: "Lees tus derechos y firmas", body: "Tienes 3 días hábiles para cancelar sin costo. Nada se trabaja antes." },
      { title: "Revisas tu reporte en la app", body: "Tú decides qué está mal. Nadie decide por ti." },
      { title: "El equipo envía tus cartas", body: `Los burós tienen unos ${CASE_RESPONSE_DAYS} días para responder. Ves cada paso, con fechas, en tu app.` },
    ],
    honestTitle: "Lo que no hacemos",
    honest: [
      "No prometemos resultados: ni puntos, ni fechas, ni aprobaciones. Los burós deciden y los resultados varían.",
      "No disputamos nada que tú digas que es correcto.",
      `Nunca le des tu número de Seguro Social ni tu reporte a ${n}. Tus datos los das tú, en tu propia cuenta.`,
    ],
    sharingTitle: `${n} y tu avance`,
    sharing: `Si quieres, puedes dejar que ${n} vea cómo va tu caso, sin ver tu crédito. Es tu decisión y la puedes quitar cuando quieras.`,
    fees: commissionsEnabled ? `${n} recibe una comisión si te refiere a ${brand}.` : `${n} no recibe ningún pago por recomendarte.`,
    cta: "Empezar",
    footer: "Los resultados varían según cada caso.",
  };
}
